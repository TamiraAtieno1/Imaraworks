"""Payment transaction models."""
from django.db import models
from django.db.models import Q

from apps.payment_requests.models import PaymentRequest

# Module-level constants for use in constraints (class not fully defined yet)
PAYMENT_STATUS_PROCESSING = "PROCESSING"
PAYMENT_STATUS_SUCCESS = "SUCCESS"
PAYMENT_STATUS_FAILED = "FAILED"


class PaymentTransaction(models.Model):
    """One payment attempt for a payment request.

    - One SUCCESS transaction per request (enforced by DB constraint).
    - Idempotency key prevents double-charge on retry with same key.
    - Status transitions: PROCESSING -> SUCCESS | FAILED
    """

    PROCESSING = PAYMENT_STATUS_PROCESSING
    SUCCESS = PAYMENT_STATUS_SUCCESS
    FAILED = PAYMENT_STATUS_FAILED
    STATUS_CHOICES = [
        (PROCESSING, "Processing"),
        (SUCCESS, "Success"),
        (FAILED, "Failed"),
    ]

    request = models.ForeignKey(
        PaymentRequest,
        on_delete=models.PROTECT,
        related_name="payment_transactions",
    )
    # Idempotency key provided by client (or generated by view for double-click protection)
    idempotency_key = models.CharField(max_length=64, db_index=True)
    amount = models.DecimalField(max_digits=12, decimal_places=2)
    currency = models.CharField(max_length=3, default="KES")
    status = models.CharField(max_length=20, choices=STATUS_CHOICES, default=PROCESSING)
    # Provider reference (e.g., M-Pesa checkout request ID, bank transaction ID)
    provider_reference = models.CharField(max_length=100, blank=True)
    provider_reason = models.TextField(blank=True)
    # Gateway used for this attempt
    gateway = models.CharField(max_length=50, default="mock")
    # Timestamps
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)
    completed_at = models.DateTimeField(null=True, blank=True)

    class Meta:
        ordering = ["-created_at"]
        constraints = [
            # One SUCCESS transaction per request (the "never pay twice" guarantee)
            models.UniqueConstraint(
                fields=["request"],
                condition=Q(status=PAYMENT_STATUS_SUCCESS),
                name="one_successful_payment_per_request",
            ),
            # Idempotency key is unique per request (prevents replay with different key on same request)
            models.UniqueConstraint(
                fields=["request", "idempotency_key"],
                name="unique_idempotency_key_per_request",
            ),
        ]

    def __str__(self):
        return f"PaymentTransaction #{self.pk} ({self.status}) for Request #{self.request_id}"


class PaymentGatewayConfig(models.Model):
    """Configuration for a payment gateway (e.g., API keys, environment).

    Only one active config per gateway name.
    """
    name = models.CharField(max_length=50, unique=True)  # e.g., "mock", "mpesa", "bank"
    is_active = models.BooleanField(default=True)
    config = models.JSONField(default=dict, blank=True)  # gateway-specific settings
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    def __str__(self):
        return f"{self.name} ({'active' if self.is_active else 'inactive'})"
